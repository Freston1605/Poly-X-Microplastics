"""Interface translation. English is the source language; the rest are catalogs.

Every user-facing string is written in English and wrapped in ``_()``::

    from polyx.core.i18n import _
    button = QPushButton(_("Open folder…"))

The msgid *is* the English sentence. Other languages live in standard
gettext catalogs under ``polyx/locales/<tag>/LC_MESSAGES/messages.po`` and
are compiled to ``.mo``. Extraction and validation are Babel's job, driven
from ``pyproject.toml`` (see ``tools/i18n``).

Why gettext instead of Qt's ``.ts``/``.qm``
-------------------------------------------
One catalog serves the whole program: the interface, the HTML report, the
command line and the training summary. It is the format every translation
editor and service can open, and it is the one that validates placeholders
at build time. Qt's own translations are loaded alongside ours so native
dialogs follow the interface too.

Resolution
----------
``POLYX_LOCALE`` if set, otherwise the user's saved preference, otherwise
the system locale, otherwise English. A regional tag falls back through its
language (``es_AR`` -> ``es``) and then to English, which is also the
msgid: for a language that is only half translated, the English text is
the correct answer, not an error.

What is deliberately *not* translated
--------------------------------------
Log messages, event names, ``run.json`` keys and CSV column headers. They
are a machine contract: a report or a run folder must read the same in
every language, and its numbers keep dot decimals and ISO dates.
"""

from __future__ import annotations

import gettext as _gettext
import hashlib
import locale
import logging
import os
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

from polyx.core import preferences

_log = logging.getLogger(__name__)

DOMAIN = "messages"
LOCALES_DIR = Path(__file__).resolve().parent.parent / "locales"

#: Generated by ``tools/i18n`` for a developer's eye; not a shipped language.
PSEUDO_TAG = "qps_ploc"

DEFAULT_LANGUAGE = "en"

_language = DEFAULT_LANGUAGE
_catalog: _gettext.NullTranslations = _gettext.NullTranslations()
_subscribers: list[Callable[[str], None]] = []


# ── Message resolution ─────────────────────────────────────────────
def _(message: str) -> str:
    """Translate ``message`` into the active language."""
    return _catalog.gettext(message)


def ngettext(singular: str, plural: str, n: int) -> str:
    """Translate a plural pair for ``n`` using the catalog's plural rules."""
    return _catalog.ngettext(singular, plural, n)


def pgettext(context: str, message: str) -> str:
    """Translate ``message`` disambiguated by ``context``."""
    return _catalog.pgettext(context, message)


def npgettext(context: str, singular: str, plural: str, n: int) -> str:
    """Plural translation disambiguated by ``context``."""
    result = _catalog.npgettext(context, singular, plural, n)
    return result


def N_(message: str) -> str:
    """Mark a string for extraction without translating it now.

    Use it where a string is stored and resolved later — a table of section
    titles, a description list — so the extractor still sees it.
    """
    return message


class LazyString:
    """A message id that resolves when it is displayed.

    Module-level constants that reach the interface cannot call ``_()`` at
    import time: that would freeze the language of the moment. Wrapping them
    keeps the id and resolves it on ``str()``.
    """

    __slots__ = ("_message",)

    def __init__(self, message: str) -> None:
        self._message = message

    def __str__(self) -> str:
        return _(self._message)

    def __format__(self, spec: str) -> str:
        return format(str(self), spec)

    def __repr__(self) -> str:
        return f"LazyString({self._message!r})"

    def __eq__(self, other: object) -> bool:
        return str(self) == str(other)

    __hash__ = None  # type: ignore[assignment]  # equality is language-dependent

    def __bool__(self) -> bool:
        return bool(self._message)


def lazy(message: str) -> LazyString:
    """A message id resolved at display time (see :class:`LazyString`)."""
    return LazyString(message)


# ── Language resolution ────────────────────────────────────────────
def _normalise(tag: str) -> str:
    return tag.strip().replace("-", "_")


def _candidates(tag: str) -> list[str]:
    """Exact tag, then its language. English is the caller's fallback."""
    normalised = _normalise(tag).lower()
    out: list[str] = []
    if normalised:
        out.append(normalised)
        language_part = normalised.split("_", 1)[0]
        if language_part != normalised:
            out.append(language_part)
    return out


def _available() -> set[str]:
    """Locale tags that have a catalog, plus the source language."""
    found = {DEFAULT_LANGUAGE}
    if LOCALES_DIR.is_dir():
        found.update(path.name for path in LOCALES_DIR.iterdir() if path.is_dir())
    return found


def _display_name(tag: str) -> str:
    """The language's own endonym, so a new catalog needs no Python entry."""
    if tag == DEFAULT_LANGUAGE:
        return "English"
    try:
        from babel import Locale

        return Locale.parse(tag).get_display_name(DEFAULT_LANGUAGE) or tag
    except (ImportError, ValueError):
        return tag


def resolve(tag: str) -> str | None:
    """The catalog for ``tag``'s chain, or ``None`` when the language has none.

    A regional tag falls back to its language (``es_AR`` -> ``es``). English is
    *not* appended: the caller decides how to degrade, so an explicitly chosen
    language with no catalog is a logged error instead of a silent switch.
    """
    available = _available()
    for candidate in _candidates(tag):
        if candidate in available:
            return candidate
    return None


def _detect_system_language() -> str:
    try:
        code = locale.getlocale()[0] or ""
    except (ValueError, TypeError):
        code = ""
    if not code:
        code = os.environ.get("LANG") or os.environ.get("LC_ALL") or ""
    return _normalise(code).lower() or DEFAULT_LANGUAGE


def _cached_mo(po_path: Path) -> Path | None:
    """Compile ``po_path`` into a cache directory, or ``None`` without Babel.

    The cache key includes the catalog's path: two checkouts (a worktree and
    the main clone, or two agents working in parallel) must not share a
    compiled file, or the last one to run wins and the other reads the wrong
    translations.
    """
    tag = po_path.parent.parent.name
    try:
        from babel.messages.mofile import write_mo
        from babel.messages.pofile import read_po
    except ImportError:
        return None
    digest = hashlib.sha256(str(po_path.resolve()).encode("utf-8")).hexdigest()[:10]
    target = Path(tempfile.gettempdir()) / "polyx-locales" / f"{tag}-{digest}" / f"{DOMAIN}.mo"
    try:
        if target.is_file() and target.stat().st_mtime >= po_path.stat().st_mtime:
            return target
    except OSError:
        pass
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        with po_path.open("rb") as source, target.open("wb") as destination:
            write_mo(destination, read_po(source))
    except (OSError, ValueError) as exc:
        _log.error("could not compile %s: %s", po_path, exc)
        return None
    return target


def _load(tag: str) -> _gettext.NullTranslations | None:
    if tag == DEFAULT_LANGUAGE:
        return _gettext.NullTranslations()
    base = LOCALES_DIR / tag / "LC_MESSAGES"
    compiled = base / f"{DOMAIN}.mo"
    if not compiled.is_file():
        source = base / f"{DOMAIN}.po"
        if not source.is_file():
            return None
        compiled = _cached_mo(source)
        if compiled is None:
            _log.error(
                "no compiled catalog for %r and Babel is not installed; "
                "run `python tools/i18n/cli.py compile`",
                tag,
            )
            return None
    try:
        with compiled.open("rb") as handle:
            return _gettext.GNUTranslations(handle)
    except (OSError, ValueError) as exc:
        _log.error("could not read %s: %s", compiled, exc)
        return None


def carry() -> str:
    """Resolve the language once, in precedence order."""
    global _language, _catalog  # noqa: PLW0603
    requested = os.environ.get("POLYX_LOCALE", "").strip()
    explicit = bool(requested)
    if not requested:
        saved = preferences.get("locale")
        requested = saved if isinstance(saved, str) else ""
        explicit = bool(requested)
    if not requested:
        requested = _detect_system_language()
    resolved = resolve(requested)
    if resolved is None:
        if explicit:
            _log.error("no catalog for %r; falling back to %r", requested, DEFAULT_LANGUAGE)
        resolved = DEFAULT_LANGUAGE
    catalog = _load(resolved)
    if catalog is None:
        resolved = DEFAULT_LANGUAGE
        catalog = _gettext.NullTranslations()
    _language = resolved
    _catalog = catalog
    return _language


def language() -> str:
    """The active locale tag."""
    return _language


def available_languages() -> dict[str, str]:
    """Locale tag -> display name, discovered from the catalog directories.

    Adding a language is creating ``locales/<tag>/LC_MESSAGES/messages.po``:
    no Python change, because the directory *is* the registration and Babel
    supplies the display name.
    """
    return {tag: _display_name(tag) for tag in sorted(_available()) if tag != PSEUDO_TAG}


def set_language(tag: str) -> bool:
    """Switch the active language immediately.

    Returns ``False`` when no catalog exists for the requested tag; the
    current language is kept and the failure is logged, never silently
    rendered as English.
    """
    global _language, _catalog  # noqa: PLW0603
    resolved = resolve(tag)
    if resolved is None:
        _log.error("no catalog for %r; keeping %r", tag, _language)
        return False
    catalog = _load(resolved)
    if catalog is None:
        return False
    _language = resolved
    _catalog = catalog
    preferences.write(locale=resolved)
    for function in _subscribers:
        try:
            function(resolved)
        except Exception:  # noqa: BLE001
            _log.exception("language subscriber failed")
    return True


def when_changing(function: Callable[[str], None]) -> None:
    """Register a callback run after every successful language change."""
    _subscribers.append(function)


def catalog_info() -> dict[str, Any]:
    """What the active catalog is, for diagnostics and tests."""
    return {"language": _language, "locales": str(LOCALES_DIR)}


carry()
