"""Report registry and document shell: section list, presets, anchors, assembly.

``SECTIONS`` / ``IDS_SECTIONS`` / ``PRESETS`` specify the catalog. The
document shell assembles cover, TOC and numbered sections; ``NUM`` is the
placeholder replaced by the assembler so section builders need not know
their final numbers.

Re-exported from ``polyx.gui.report._common`` (removed in refactor) to keep the package surface
stable (the 76-name contract) and because call sites import from there.
"""

from __future__ import annotations

from polyx.core.i18n import N_, _, language

from .markup import _esc, _report_css

SECTIONS = [
    ("resumen", N_("Summary")),
    ("metodos", N_("Methods")),
    ("calibracion", N_("Scale calibration")),
    ("forma", N_("Particle shape and size")),
    ("talla_carpetas", N_("Size by folder and by photo (comparison between sites)")),
    ("profundidad", N_("Depth profile of the core")),
    ("fichas", N_("Measured-particle cards (sample)")),
    ("resultados", N_("Overall results")),
    ("modelos", N_("Per-model summary")),
    ("errores", N_("Error analysis")),
    ("comparacion", N_("Model comparison")),
    ("galeria", N_("Per-image gallery")),
    ("conteo", N_("Counts by sample and polymer type")),
    ("referencias", N_("References")),
]

IDS_SECTIONS = [s[0] for s in SECTIONS]

# Frequently used combinations. They exist because the real problem was not that choosing
# was impossible, but that choosing ten checkboxes one by one is tedious and
# nobody does it: with a preset the short report is one click away.
PRESETS = {
    "completo": IDS_SECTIONS,
    "resumen": ["resumen", "calibracion", "forma", "conteo", "galeria"],
    "metodologico": [
        "resumen",
        "metodos",
        "calibracion",
        "forma",
        "fichas",
        "modelos",
        "errores",
        "comparacion",
        "referencias",
    ],
}

# Marker that is replaced by the final section number during assembly.
# Numbers cannot be written by hand in the titles because they depend on which
# other sections were requested.
NUM = "@@N@@"


# Legacy anchor names, to avoid breaking links to reports already
# distributed. A new section does NOT have to appear here: its own id already
# serves as an anchor. This dictionary was a second list to keep in
# sync with SECCIONES, and adding `profundidad` crashed with
# KeyError -- exactly what SECCIONES avoids by being a single list.
_ANCHORS = {
    "resumen": "abstract",
    "metodos": "methods",
    "calibracion": "calib",
    "resultados": "results",
    "modelos": "models",
    "errores": "errors",
    "comparacion": "compare",
    "galeria": "gallery",
    "referencias": "refs",
}


def anchor(sid: str) -> str:
    """Anchor name for a section id: legacy alias if any, the id itself otherwise."""
    return _ANCHORS.get(sid, sid)


def _document_html(alive, active, status_note: str = "") -> str:
    """Assemble the final document: cover header, TOC, numbered sections, footer.

    ``vivas`` arrives as (id, translated title, body) tuples in SECCIONES
    order, already filtered to the requested sections that have content.
    The enumeration (SECCIONES order, start=1), the ``<h2>`` titles and the
    ``{NUM}`` placeholder substitution all live here because this helper is
    the only place that knows the final order; moving or reordering them is
    byte-visible in the frozen render (MEM090).

    ``status_note`` is the visible failed/aborted banner. It lives in the
    document shell and not in a section so a partial run cannot be presented
    as complete just because the user unchecked the section carrying it.
    """
    toc_html = "".join(
        f"<li><a href='#{anchor(sid)}'>{title}</a></li>" for sid, title, _unused in alive
    )
    sections_html = "".join(
        f"<h2 id='{anchor(sid)}'>{i}. {title}</h2>\n{body.replace(NUM, str(i))}\n"
        for i, (sid, title, body) in enumerate(alive, start=1)
    )
    # Keep the finished-run render byte-identical to the frozen baseline: an
    # absent banner must not leave an empty line behind.
    status_block = f"{status_note}\n\n" if status_note else ""

    return f"""<!doctype html>
<html lang='{language()}'><head><meta charset='utf-8'>
<title>{_("Detection report")} · Poly-X</title>
<style>{_report_css()}</style></head><body>
<div class='container'>

<header class='cover'>
  <div class='kicker'>Poly-X · {_("Detection report")}</div>
  <h1>{_("Microplastics detection report")}<br>{_("by Nile Red fluorescence")}</h1>
  <p class='meta'><strong>{_("Author:")}</strong> Cristofher Ferrada &middot;
    <strong>{_("Models:")}</strong> {_esc(", ".join(s.alias for s in active)) or "—"}</p>
</header>

{status_block}<div class='toc'>
  <h3>📑 {_("Contents")}</h3>
  <ol>{toc_html}</ol>
</div>

{sections_html}
<footer>
  © Cristofher Ferrada · {_("Generated by Poly-X")}<br>
  {_("Microplastics detection suite by Nile Red fluorescence (254 nm) and AI (YOLO v8/v11).")}
</footer>
</div></body></html>
"""
