"""Import an external CVAT COCO export as the canonical segmentation dataset.

COCO instance JSON is the canonical mask format of the headless pipeline. The
masks are produced outside Poly-X (CVAT by default; another tool is acceptable
while it emits COCO polygons), audited with the project's existing dataset
audit and stored as a versioned tool output under the user data dir. Nothing
here writes into a detection run folder — ADR-0002 keeps those box-only — and
no mask is ever generated by this module: a machine-generated annotation is a
reason to reject the export, not to repair it.
"""

from __future__ import annotations

import json
import re
from copy import deepcopy
from pathlib import Path
from typing import Any

from polyx.core.i18n import _
from polyx.core.provenance import sha256_file
from polyx.core.quality.dataset_audit import DatasetAudit, audit_coco_masks
from polyx.pipeline.artifacts import write_json

#: The documented target of the first annotation batch. Kept in the artifact
#: so the goal travels with the data instead of living only in the ADR.
FIRST_BATCH_TARGET = (
    "A first stratified batch of roughly ten plates, spanning every study class "
    "(PET, PP and LDPE) and the imaging domains represented in the study, so each "
    "class appears in both the training and validation folds before a larger "
    "annotation effort is committed."
)

#: Provenance values that mark a mask as machine-generated. They are diagnostics
#: or proposal generators (SAM2, Otsu, YOLO-seg), never ground truth. A value
#: matches when one of these appears as a whole token or hyphenated phrase, so
#: "SAM2 automatic" is caught while "same sample" is not.
MACHINE_GENERATOR_TOKENS = frozenset(
    {
        "machine-generated",
        "otsu",
        "pseudo-mask",
        "sam",
        "sam2",
        "yolo-seg",
        "yoloseg",
    }
)

#: Fields an annotation tool may use to record where a mask came from.
_PROVENANCE_FIELDS = ("source", "generator", "provenance", "mask_source", "model")


class CocoImportError(ValueError):
    """The export cannot be accepted as segmentation ground truth."""


def _as_int(value: Any, what: str) -> int:
    """A positive-or-zero integer field, with a message naming the field."""
    if isinstance(value, bool) or not isinstance(value, int):
        raise CocoImportError(f"COCO {what} must be an integer, got {value!r}")
    return value


def _validate_export(coco: dict[str, Any]) -> None:
    """Reject a structurally broken COCO object before any mask is audited."""
    seen_images: set[int] = set()
    for image in coco["images"]:
        if not isinstance(image, dict):
            raise CocoImportError("every COCO image must be an object")
        image_id = _as_int(image.get("id"), "image id")
        if image_id in seen_images:
            raise CocoImportError(f"duplicate COCO image id: {image_id}")
        seen_images.add(image_id)
        name = image.get("file_name")
        if not isinstance(name, str) or not name.strip():
            raise CocoImportError(f"COCO image {image_id} has no file_name")
        if _as_int(image.get("width"), f"image {image_id} width") <= 0:
            raise CocoImportError(f"COCO image {image_id} has a non-positive width")
        if _as_int(image.get("height"), f"image {image_id} height") <= 0:
            raise CocoImportError(f"COCO image {image_id} has a non-positive height")

    seen_categories: set[int] = set()
    for category in coco["categories"]:
        if not isinstance(category, dict):
            raise CocoImportError("every COCO category must be an object")
        category_id = _as_int(category.get("id"), "category id")
        if category_id in seen_categories:
            raise CocoImportError(f"duplicate COCO category id: {category_id}")
        seen_categories.add(category_id)
        if not str(category.get("name") or "").strip():
            raise CocoImportError(f"COCO category {category_id} has no name")

    seen_annotations: set[int] = set()
    for annotation in coco["annotations"]:
        if not isinstance(annotation, dict):
            raise CocoImportError("every COCO annotation must be an object")
        annotation_id = _as_int(annotation.get("id"), "annotation id")
        if annotation_id in seen_annotations:
            raise CocoImportError(f"duplicate COCO annotation id: {annotation_id}")
        seen_annotations.add(annotation_id)
        _as_int(annotation.get("image_id"), f"annotation {annotation_id} image_id")
        _as_int(annotation.get("category_id"), f"annotation {annotation_id} category_id")


def read_export(export: Path) -> tuple[dict[str, Any], Path, Path]:
    """Return ``(coco, json_path, images_root)`` for a CVAT COCO export.

    ``export`` may be the export folder or an instance JSON inside it. Exactly
    one candidate JSON is accepted: silently picking one of several tasks would
    import a dataset the caller did not choose.
    """
    export = Path(export).expanduser().resolve()
    if export.is_file():
        json_path = export
        export_dir = export.parent.parent if export.parent.name == "annotations" else export.parent
    elif export.is_dir():
        candidates = sorted((export / "annotations").glob("*.json")) or sorted(
            export.glob("*.json")
        )
        if not candidates:
            raise CocoImportError(f"no COCO instance JSON found in {export.name}")
        if len(candidates) > 1:
            names = ", ".join(candidate.name for candidate in candidates)
            raise CocoImportError(f"multiple COCO instance JSON files found: {names}")
        json_path = candidates[0]
        export_dir = export
    else:
        raise CocoImportError(f"COCO export does not exist: {export}")

    try:
        coco = json.loads(json_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise CocoImportError(f"could not read COCO instance JSON: {exc}") from exc
    if not isinstance(coco, dict):
        raise CocoImportError("COCO instance JSON must be an object")
    for key in ("images", "annotations", "categories"):
        if not isinstance(coco.get(key), list):
            raise CocoImportError(f"COCO instance JSON needs a '{key}' list")
    _validate_export(coco)

    images_root = export_dir / "images" if (export_dir / "images").is_dir() else export_dir
    return coco, json_path, images_root


def _provenance_values(entity: dict[str, Any]) -> list[str]:
    """The strings an annotation tool may use to describe a mask's origin."""
    values: list[str] = []
    attributes = entity.get("attributes")
    if isinstance(attributes, dict):
        for key, value in attributes.items():
            if str(key).lower() in _PROVENANCE_FIELDS:
                values.append(str(value))
    elif isinstance(attributes, list):
        values.extend(
            str(item.get("value", ""))
            for item in attributes
            if isinstance(item, dict) and str(item.get("name", "")).lower() in _PROVENANCE_FIELDS
        )
    values.extend(str(entity[field]) for field in _PROVENANCE_FIELDS if field in entity)
    return values


def _tokens(value: str) -> set[str]:
    """Whole words and hyphenated phrases of a provenance value."""
    words = [word for word in re.split(r"[^a-z0-9]+", value.lower()) if word]
    found = set(words)
    for size in (2, 3):
        for index in range(len(words) - size + 1):
            found.add("-".join(words[index : index + size]))
    return found


def machine_generated_sources(entity: dict[str, Any]) -> set[str]:
    """Machine-generator tokens carried by one annotation or image.

    CVAT records annotation metadata in ``attributes`` (a mapping or a list of
    name/value pairs); some tools add a top-level ``source``. A marker naming a
    machine generator makes the mask ineligible as ground truth.
    """
    found: set[str] = set()
    for value in _provenance_values(entity):
        found |= _tokens(value) & MACHINE_GENERATOR_TOKENS
    return found


def reject_machine_masks(coco: dict[str, Any]) -> None:
    """Reject the whole export if any mask or image is machine-generated.

    The rejection is all-or-nothing: a mixed export cannot be partially trusted
    as ground truth without a per-annotation review step this tool does not
    provide. SAM2, Otsu and YOLO-seg remain diagnostics and proposal
    generators only.
    """
    sources = (
        ("annotation", coco.get("annotations", [])),
        ("image", coco.get("images", [])),
    )
    for kind, entities in sources:
        for entity in entities:
            generators = machine_generated_sources(entity)
            if generators:
                raise CocoImportError(
                    "machine-generated mask cannot be recorded as ground truth: "
                    f"{kind} {entity.get('id')} has source {', '.join(sorted(generators))}"
                )


def _safe_relative(file_name: str) -> Path:
    """A referenced image path that cannot escape the export folder."""
    candidate = Path(file_name)
    if (
        not file_name
        or candidate.is_absolute()
        or ".." in candidate.parts
        or candidate.name in {"", "."}
    ):
        raise CocoImportError(f"unsafe COCO image file_name: {file_name!r}")
    return candidate


def read_images(coco: dict[str, Any], images_root: Path, json_path: Path) -> dict[str, bytes]:
    """Read every referenced image before anything is written to disk.

    A missing or unsafe image therefore fails the import while no canonical
    version exists, instead of leaving a half-copied dataset behind.
    """
    payloads: dict[str, bytes] = {}
    for image in coco["images"]:
        relative = _safe_relative(str(image["file_name"]))
        key = relative.as_posix()
        if key in payloads:
            raise CocoImportError(f"duplicate COCO image file_name: {key}")
        for base in (images_root, json_path.parent, json_path.parent.parent):
            path = base / relative
            if path.is_file():
                payloads[key] = path.read_bytes()
                break
        else:
            raise CocoImportError(f"COCO image is missing from the export: {key}")
    return payloads


def _validated_name(name: str) -> str:
    """A dataset name that is exactly one folder below the dataset root."""
    candidate = Path(name)
    if name in {"", ".", ".."} or candidate.is_absolute() or candidate.name != name:
        raise CocoImportError(f"invalid dataset name: {name!r}")
    return name


def _next_version(name_dir: Path) -> str:
    """The next ``vN`` version, leaving earlier imports untouched."""
    highest = 0
    if name_dir.is_dir():
        for child in name_dir.iterdir():
            if child.is_dir() and child.name.startswith("v") and child.name[1:].isdigit():
                highest = max(highest, int(child.name[1:]))
    return f"v{highest + 1}"


def store_dataset(
    coco: dict[str, Any],
    audit: DatasetAudit,
    json_path: Path,
    images: dict[str, bytes],
    root: Path,
    name: str,
) -> tuple[Path, dict[str, Any]]:
    """Write the validated export as a versioned tool output and its manifest.

    The canonical JSON is rewritten so every ``file_name`` resolves inside the
    stored version (``images/<original name>``); the export folder is then
    irrelevant to later conversions.
    """
    name = _validated_name(name)
    name_dir = Path(root) / name
    version = _next_version(name_dir)
    store = name_dir / version
    images_dir = store / "images"
    images_dir.mkdir(parents=True, exist_ok=False)

    canonical = deepcopy(coco)
    hashes: dict[str, str] = {}
    for image in canonical["images"]:
        relative = _safe_relative(str(image["file_name"]))
        destination = images_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(images[relative.as_posix()])
        image["file_name"] = (Path("images") / relative).as_posix()
        hashes[image["file_name"]] = sha256_file(destination)
    write_json(canonical, store / "dataset.json")
    hashes = {"dataset.json": sha256_file(store / "dataset.json"), **hashes}

    distribution = {
        split: dict(audit.per_class[split])
        for split in ("train", "val", "test")
        if audit.per_class.get(split)
    }
    manifest: dict[str, Any] = {
        "schema_version": 1,
        "format": "coco_instances",
        "artifact_class": "tool_output",
        "name": name,
        "version": version,
        "source_tool": "cvat",
        "source_export": json_path.name,
        "source_export_sha256": sha256_file(json_path),
        "ground_truth": {
            "policy": "human-only",
            "machine_generated_rejected": 0,
            "forbidden_sources": sorted(MACHINE_GENERATOR_TOKENS),
        },
        "class_distribution": distribution,
        "first_batch_target": FIRST_BATCH_TARGET,
        "counts": {
            "images": len(canonical["images"]),
            "annotations": len(canonical["annotations"]),
            "categories": len(canonical["categories"]),
        },
        "dataset_hashes": hashes,
    }
    write_json(manifest, store / "manifest.json")
    write_json(audit_as_dict(audit), store / "audit.json")
    return store, manifest


def audit_as_dict(audit: DatasetAudit) -> dict[str, Any]:
    """Plain, JSON-serialisable view of one dataset audit."""
    return {
        "ok": audit.ok,
        "class_names": list(audit.class_names),
        "per_class": {split: dict(counts) for split, counts in audit.per_class.items()},
        "box_area_median": dict(audit.box_area_median),
        "findings": [
            {
                "level": item.level,
                "code": item.code,
                "parameters": item.parameters,
            }
            for item in audit.findings
        ],
    }


def write_import_report(
    path: Path, store: Path, manifest: dict[str, Any], audit: DatasetAudit
) -> None:
    """The command-facing report: distribution, store location and audit."""
    lines = [
        f"# {_('COCO segmentation dataset import')}",
        "",
        f"- {_('Dataset')}: {manifest['name']}",
        f"- {_('Version')}: {manifest['version']}",
        f"- {_('Canonical tool output')}: {store}",
        f"- {_('Source')}: {manifest['source_tool']} COCO instances export",
        f"- {_('Source JSON')}: {manifest['source_export']}",
        f"- {_('Ground-truth policy')}: {manifest['ground_truth']['policy']}",
        "",
        f"## {_('Class distribution')}",
        "",
    ]
    for split, counts in manifest["class_distribution"].items():
        rendered = ", ".join(f"{name}={count}" for name, count in counts.items())
        lines.append(f"- {split}: {rendered}")
    lines.extend(
        [
            "",
            f"## {_('First stratified batch')}",
            "",
            _(
                "A first stratified batch of roughly ten plates, spanning every study class "
                "(PET, PP and LDPE) and the imaging domains represented in the study, so each "
                "class appears in both the training and validation folds before a larger "
                "annotation effort is committed."
            ),
            "",
            f"## {_('Audit')}",
            "",
        ]
    )
    lines.append(f"- ok: {str(audit.ok).lower()}")
    lines.extend(f"- {finding.level}: {finding.title}" for finding in audit.findings)
    lines.append("")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines), encoding="utf-8")


def import_coco_dataset(export: Path, root: Path, name: str) -> dict[str, Any]:
    """Validate, audit and store one CVAT COCO export; never write a run folder.

    Every rejection path runs before a version folder is created, so a failed
    import leaves no canonical dataset on disk.
    """
    coco, json_path, images_root = read_export(export)
    reject_machine_masks(coco)
    audit = audit_coco_masks(coco)
    if not audit.ok:
        problems = [f"{finding.title}: {finding.detail}" for finding in audit.findings]
        raise CocoImportError("dataset audit failed: " + "; ".join(problems))
    images = read_images(coco, images_root, json_path)
    store, manifest = store_dataset(coco, audit, json_path, images, Path(root), name)
    return {
        "store": store,
        "manifest": manifest,
        "audit": audit,
        "coco": coco,
    }
