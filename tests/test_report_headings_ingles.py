"""Durable gate: report headings render English regardless of UI language.

M006/S05 removed the last code-facing text gap in the pipeline report: twelve
headings were raw Spanish literals interpolated outside the ``tr()`` layer, so
the English render still showed ``Muestra (imagen)``, ``Clase``, ``Fibras``,
``Imagen``, ``menor/mediana/mayor`` with ``µm``, and the confusion-matrix
labels. They are now English literals at their ``polyx/gui/report/`` render
sites, generated by the D033 heading bridge (S05/T01); the runtime
``tr()`` dictionary and the SECTIONS titles stay untouched.

This module proves the fix from three angles:

1. the benign and complete renders read English in the ``en`` baseline;
2. the same literals also read English in the ``es`` render, proving they no
   longer follow the UI language (the ``tr()`` prose in that render must stay
   Spanish, so only the presence of the English labels is asserted there);
3. an AST scan of the report package rejects any raw Spanish heading literal
   added back outside ``tr()``, with an anti-vacuity case proving the scanner
   really flags the regressions it claims to catch.

The two ``baseline`` tests read the frozen HTML snapshots and are expected to
be red until S05/T03 recaptures them from the fixed code; the rest of the
module runs green on the fixed render (``-k "not baseline"``).
"""

