_HEADING_MARKERS = ("<th>", "<td>", "<h1>", "<h2>", "<h3>")


def _python_docstrings(tree: ast.AST) -> set[int]:
    """Ids of the constant nodes that are module/class/function docstrings."""
    docstrings: set[int] = set()
    owners = (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
    for node in ast.walk(tree):
        if not isinstance(node, owners):
            continue
        body = getattr(node, "body", [])
        if (
            body
            and isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)
        ):
            docstrings.add(id(body[0].value))
    return docstrings


def _heading_literals(source: str) -> list[tuple[int, str]]:
    """HTML heading/label string constants outside tr(), dicts and subscripts.

    ``tr()`` keys are the runtime dictionary and are intentionally Spanish in
    the ``es`` render, so they are excluded. Dict keys and subscript slices
    (for example ``res['mediana']``) are data lookups, not report labels.
    """
    tree = ast.parse(source)
    docstrings = _python_docstrings(tree)

    tr_contents: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "tr":
            for child in ast.walk(node):
                tr_contents.add(id(child))

    excluded = set(docstrings) | tr_contents
    for node in ast.walk(tree):
        if isinstance(node, ast.Subscript):
            excluded.add(id(node.slice))
        elif isinstance(node, ast.Dict):
            excluded.update(id(key) for key in node.keys if key is not None)

    literals: list[tuple[int, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant) or not isinstance(node.value, str):
            continue
        if id(node) in excluded:
            continue
        literal = node.value
        if any(marker in literal for marker in _HEADING_MARKERS) or (
            literal.strip() == "Muestra (imagen)"
        ):
            literals.append((node.lineno, literal))
    return literals


def _offending_headings(source: str) -> list[tuple[int, str, str]]:
    """(line, Spanish label, literal) for every raw Spanish heading literal."""
    offenders: list[tuple[int, str, str]] = []
    for line, literal in _heading_literals(source):
        for label in ROTULOS_ES | ROTULOS_ES_CON_UNIDAD:
            if label in literal:
                offenders.append((line, label, literal))  # noqa: PERF401
    return offenders


def test_no_queda_ningun_rotulo_en_espanol_fuera_de_tr():
    assert REPORT_PATHS, "no report sources found to scan"
    offenders = []
    for report_path in REPORT_PATHS:
        source = report_path.read_text(encoding="utf-8")
        for line, label, literal in _offending_headings(source):
            offenders.append((f"{report_path.name}:{line}", label, literal))
        for removed in ("LABEL_TP", "LABEL_FP", "LABEL_FN", "LABEL_MISCLS"):
            assert removed not in source, f"{removed} must not be used by {report_path.name}"
    detail = "\n  ".join(
        f"line {line}: {label!r} in {literal!r}" for line, label, literal in offenders
    )
    assert not offenders, (
        "raw Spanish report heading outside tr(); translate it at the render "
        "site with the S05 heading manifest:\n  " + detail
    )


def test_el_escanner_caza_un_rotulo_sintetico():
    """Anti-vacuity: the scanner really flags the regression it claims to."""
    synthetic = 'def render():\n    return "<th>Muestra (imagen)</th>"\n'
    assert _offending_headings(synthetic)


def test_el_escanner_ignora_los_rotulos_dentro_de_tr():
    """Anti-vacuity in the other direction: tr() keys are allowed to be Spanish."""
    synthetic = "def render():\n    return f\"{tr('<th>Clase</th>')}\"\n"
    assert not _offending_headings(synthetic)


