"""The translation gate: five ways a catalog drifts from the source tree.

Every check prints the file, the line and the offending string, because the
person fixing it is usually an agent reading a log:

- the committed template is stale (a wrapper was added or removed, or a line
  moved and the template was not regenerated);
- a catalog entry is empty, fuzzy or missing, so the user would silently get
  the English source instead of a translation;
- a placeholder set does not match between message id and translation;
- a translation call takes an f-string or ``str.format`` braces, which no
  catalog validator can check;
- a user-visible string reaches a Qt widget without a translation call.

The scan is standard-library only so the pre-commit hook can run it in its
isolated environment. Writing catalogs needs Babel; reading them does not.

The bypass scan covers the desktop interface: user-visible text there is
passed to a known Qt sink (a constructor, a setter, a dialog static). Text
that reaches the interface through a variable is invisible to a static scan,
which is why the live-switch test and the surface tests exist as well.
"""

from __future__ import annotations

import ast
import html
import re
from dataclasses import dataclass
from pathlib import Path

from tools.i18n import po
from tools.i18n.extract import KEYWORDS as TRANSLATION_CALLS
from tools.i18n.extract import iter_source_messages

TEMPLATE = Path("src/polyx/locales/messages.pot")
LOCALES = Path("src/polyx/locales")
SOURCE = Path("src/polyx")
GUI = Path("src/polyx/gui")

#: Generated by ``tools/i18n`` for a developer's eye, never a shipped locale.
PSEUDO_TAG = "qps_ploc"

STALE_TEMPLATE = "stale-template"
EMPTY_TRANSLATION = "empty-translation"
PLACEHOLDER_MISMATCH = "placeholder-mismatch"
DYNAMIC_CALL = "dynamic-call"
UNWRAPPED_STRING = "unwrapped-string"

#: Widget methods whose positional argument is visible text.
_WIDGET_METHODS: dict[str, tuple[int, ...]] = {
    "setText": (0,),
    "setWindowTitle": (0,),
    "setToolTip": (0,),
    "setStatusTip": (0,),
    "setWhatsThis": (0,),
    "setPlaceholderText": (0,),
    "setTitle": (0,),
    "setLabelText": (0,),
    "setInformativeText": (0,),
    "setDetailedText": (0,),
    "setHtml": (0,),
    "setPlainText": (0,),
    "setAccessibleName": (0,),
    "setAccessibleDescription": (0,),
    "addItem": (0,),
    "addTab": (1,),
    "addAction": (0,),
    "showMessage": (0,),
    "setPrefix": (0,),
    "setSuffix": (0,),
    # Project helpers that take display text directly.
    "card": (0,),
    "_set_status": (0,),
    "set_loaded_status": (0,),
}

#: Widget constructors whose positional argument is visible text.
_WIDGET_CONSTRUCTORS: dict[str, tuple[int, ...]] = {
    "QLabel": (0,),
    "QPushButton": (0,),
    "QCheckBox": (0,),
    "QRadioButton": (0,),
    "QGroupBox": (0,),
    "QAction": (0,),
    "QMenu": (0,),
    "QToolButton": (0,),
    "QProgressDialog": (0, 1),
    "QTableWidgetItem": (0,),
    "QListWidgetItem": (0,),
    "QTreeWidgetItem": (0,),
}

#: Static dialog methods: the class that owns them and the text arguments.
_DIALOG_STATICS: dict[str, dict[str, tuple[int, ...]]] = {
    "QMessageBox": {
        "warning": (1, 2),
        "information": (1, 2),
        "critical": (1, 2),
        "question": (1, 2),
        "about": (1, 2),
    },
    "QFileDialog": {
        "getOpenFileName": (1, 3),
        "getSaveFileName": (1, 3),
        "getOpenFileNames": (1, 3),
        "getExistingDirectory": (1,),
    },
    "QInputDialog": {
        "getItem": (1, 2),
        "getText": (1, 2),
        "getMultiLineText": (1, 2),
        "getInt": (1, 2),
        "getDouble": (1, 2),
    },
}

_TAG = re.compile(r"<[^>]*>")
_STYLE = re.compile(r"\b(?:style|class)\s*=\s*(?:'[^']*'?|\"[^\"]*\"?)")
_ENTITY = re.compile(r"&(?:[A-Za-z]+|#\d+|#x[0-9A-Fa-f]+);")
_WORD = re.compile(r"[^\W\d_]{2,}", re.UNICODE)


@dataclass(frozen=True, order=True)
class Finding:
    """One drift, located where the fix belongs."""

    path: str
    line: int
    kind: str
    detail: str

    def __str__(self) -> str:
        location = f"{self.path}:{self.line}" if self.line else self.path
        return f"{location}: {self.kind}: {self.detail}"


# ---------------------------------------------------------------------------
# Entry points.
# ---------------------------------------------------------------------------


def audit_tree(root: Path) -> list[Finding]:
    """Run every check over a checkout and return the sorted findings."""
    findings = audit_sources(root) + audit_template(root) + audit_catalogs(root)
    return sorted(set(findings))


def report(findings: list[Finding], stream=None) -> None:
    """Print one line per finding, the shape a log reader can grep."""
    import sys

    target = stream or sys.stderr
    for finding in findings:
        print(finding, file=target)


# ---------------------------------------------------------------------------
# Stale template.
# ---------------------------------------------------------------------------


def audit_template(root: Path) -> list[Finding]:
    """Compare the committed template with a fresh walk of the source tree."""
    template = root / TEMPLATE
    if not template.is_file():
        return [
            Finding(
                TEMPLATE.as_posix(),
                0,
                STALE_TEMPLATE,
                "committed template is missing; run `python tools/i18n/cli.py extract`",
            )
        ]

    source = _source_entries(root)
    committed = _template_entries(template)
    findings: list[Finding] = []

    for key in sorted(source.keys() - committed.keys(), key=_sort_key):
        locations = sorted(source[key])
        path, line = locations[0]
        findings.append(
            Finding(
                path,
                line,
                STALE_TEMPLATE,
                f"template is missing {_describe(key)}; run `python tools/i18n/cli.py extract`",
            )
        )

    for key in sorted(committed.keys() - source.keys(), key=_sort_key):
        entry = committed[key]
        findings.append(
            Finding(
                TEMPLATE.as_posix(),
                entry.lineno,
                STALE_TEMPLATE,
                f"template has {_describe(key)} that no source uses",
            )
        )

    for key in sorted(source.keys() & committed.keys(), key=_sort_key):
        expected = set(source[key])
        actual = set(committed[key].locations)
        if expected != actual:
            findings.append(
                Finding(
                    TEMPLATE.as_posix(),
                    committed[key].lineno,
                    STALE_TEMPLATE,
                    f"locations changed for {_describe(key)}: "
                    f"template {_locations(actual)}, source {_locations(expected)}",
                )
            )

    return findings


def _source_entries(root: Path) -> dict[tuple[str | None, object], list[tuple[str, int]]]:
    """Every message in the source tree, with the places it appears."""
    entries: dict[tuple[str | None, object], list[tuple[str, int]]] = {}
    source_root = root / SOURCE
    if not source_root.is_dir():
        return entries
    for path in sorted(source_root.rglob("*.py")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        relative = path.relative_to(root).as_posix()
        for message in iter_source_messages(text):
            entries.setdefault((message.context, message.message), []).append(
                (relative, message.line)
            )
    return entries


def _template_entries(template: Path) -> dict[tuple[str | None, object], po.PoEntry]:
    entries: dict[tuple[str | None, object], po.PoEntry] = {}
    for entry in po.parse_po(template.read_text(encoding="utf-8")):
        if entry.obsolete or not entry.msgid:
            continue
        entries[entry.key] = entry
    return entries


def _describe(key: tuple[str | None, object]) -> str:
    context, message = key
    if isinstance(message, tuple):
        rendered = f"plural {message[0]!r} / {message[1]!r}"
    else:
        rendered = f"msgid {message!r}"
    return f"context {context!r}: {rendered}" if context else rendered


def _sort_key(key: tuple[str | None, object]) -> tuple[str, str, str]:
    """Order keys without comparing a singular string to a plural tuple."""
    context, message = key
    return (context or "", type(message).__name__, repr(message))


def _locations(locations: set[tuple[str, int]]) -> str:
    return ", ".join(f"{path}:{line}" for path, line in sorted(locations))


# ---------------------------------------------------------------------------
# Catalog translations.
# ---------------------------------------------------------------------------


def audit_catalogs(root: Path) -> list[Finding]:
    """Check every shipped catalog: present, translated, placeholders intact."""
    template = root / TEMPLATE
    template_entries = _template_entries(template) if template.is_file() else {}
    findings: list[Finding] = []

    for catalog in sorted((root / LOCALES).glob("*/LC_MESSAGES/*.po")):
        if catalog.parent.parent.name == PSEUDO_TAG:
            continue
        relative = catalog.relative_to(root).as_posix()
        entries = [
            entry
            for entry in po.parse_po(catalog.read_text(encoding="utf-8"))
            if not entry.obsolete
        ]
        by_key = {entry.key: entry for entry in entries if entry.msgid}
        findings.extend(_catalog_findings(relative, entries))

        for key in sorted(template_entries.keys() - by_key.keys(), key=_sort_key):
            template_entry = template_entries[key]
            location = (
                template_entry.locations[0]
                if template_entry.locations
                else (TEMPLATE.as_posix(), 0)
            )
            findings.append(
                Finding(
                    location[0],
                    location[1],
                    EMPTY_TRANSLATION,
                    f"{_describe(key)} is missing from {relative}",
                )
            )

    return findings


def _catalog_findings(relative: str, entries: list[po.PoEntry]) -> list[Finding]:
    findings: list[Finding] = []
    for entry in entries:
        if not entry.msgid:
            continue
        if entry.fuzzy:
            findings.append(
                Finding(
                    relative,
                    entry.lineno,
                    EMPTY_TRANSLATION,
                    f"{_describe(entry.key)} is fuzzy and is ignored at runtime",
                )
            )
            continue
        if entry.is_plural:
            findings.extend(_plural_findings(relative, entry))
        else:
            findings.extend(_singular_findings(relative, entry))
    return findings


def _singular_findings(relative: str, entry: po.PoEntry) -> list[Finding]:
    if not entry.msgstr.strip():
        return [
            Finding(
                relative,
                entry.lineno,
                EMPTY_TRANSLATION,
                f"{_describe(entry.key)} has an empty translation",
            )
        ]
    return _placeholder_findings(relative, entry, entry.msgid, entry.msgstr, "translation")


def _plural_findings(relative: str, entry: po.PoEntry) -> list[Finding]:
    forms = sorted(entry.msgstr_plural)
    if not forms:
        return [
            Finding(
                relative,
                entry.lineno,
                EMPTY_TRANSLATION,
                f"{_describe(entry.key)} has no plural translation",
            )
        ]
    findings: list[Finding] = []
    for index in forms:
        value = entry.msgstr_plural[index]
        if not value.strip():
            findings.append(
                Finding(
                    relative,
                    entry.lineno,
                    EMPTY_TRANSLATION,
                    f"{_describe(entry.key)} has an empty plural form {index}",
                )
            )
            continue
        expected_id = entry.msgid if index == 0 else entry.msgid_plural
        findings.extend(
            _placeholder_findings(
                relative, entry, expected_id or entry.msgid, value, f"plural form {index}"
            )
        )
    return findings


def _placeholder_findings(
    relative: str,
    entry: po.PoEntry,
    message_id: str,
    translation: str,
    label: str,
) -> list[Finding]:
    if po.has_braces(translation):
        return [
            Finding(
                relative,
                entry.lineno,
                PLACEHOLDER_MISMATCH,
                f"{label} for {_describe(entry.key)} uses braces: {translation!r}",
            )
        ]
    expected = po.format_placeholders(message_id)
    actual = po.format_placeholders(translation)
    if expected == actual:
        return []
    return [
        Finding(
            relative,
            entry.lineno,
            PLACEHOLDER_MISMATCH,
            f"{label} for {_describe(entry.key)} expects {sorted(expected)} "
            f"but has {sorted(actual)}",
        )
    ]


# ---------------------------------------------------------------------------
# Dynamic translation calls and unwrapped widget text.
# ---------------------------------------------------------------------------


def audit_sources(root: Path) -> list[Finding]:
    """Check translation-call arguments and user-visible widget text."""
    findings: list[Finding] = []
    source_root = root / SOURCE
    if not source_root.is_dir():
        return findings

    for path in sorted(source_root.rglob("*.py")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        relative = path.relative_to(root).as_posix()
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        findings.extend(_dynamic_findings(relative, tree))
        if path.is_relative_to(root / GUI):
            findings.extend(_unwrapped_findings(relative, tree))

    return findings


def _dynamic_findings(relative: str, tree: ast.AST) -> list[Finding]:
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        function = _call_name(node.func)
        if function not in TRANSLATION_CALLS:
            continue
        for argument in node.args:
            if isinstance(argument, ast.JoinedStr):
                findings.append(
                    Finding(
                        relative,
                        argument.lineno,
                        DYNAMIC_CALL,
                        f"f-string passed to {function}(); use a named %(placeholder)s",
                    )
                )
            elif (
                isinstance(argument, ast.Constant)
                and isinstance(argument.value, str)
                and po.has_braces(argument.value)
            ):
                findings.append(
                    Finding(
                        relative,
                        argument.lineno,
                        DYNAMIC_CALL,
                        f"positional braces in {function}(): {argument.value!r}",
                    )
                )
            elif (
                isinstance(argument, ast.Call)
                and isinstance(argument.func, ast.Attribute)
                and argument.func.attr in {"format", "format_map"}
            ):
                findings.append(
                    Finding(
                        relative,
                        argument.lineno,
                        DYNAMIC_CALL,
                        f"str.format passed to {function}(); use a named %(placeholder)s",
                    )
                )
    return findings


def _unwrapped_findings(relative: str, tree: ast.AST) -> list[Finding]:
    parents = {
        id(child): parent for parent in ast.walk(tree) for child in ast.iter_child_nodes(parent)
    }
    findings: list[Finding] = []
    seen: set[tuple[int, str]] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        indices = _sink_indices(node)
        if indices is None:
            continue
        for index in indices:
            if index >= len(node.args):
                continue
            for literal in _literal_parts(node.args[index]):
                if _inside_translation(literal, parents):
                    continue
                visible = _visible_text(literal.value)
                if not _WORD.search(visible):
                    continue
                key = (literal.lineno, literal.value)
                if key in seen:
                    continue
                seen.add(key)
                findings.append(
                    Finding(
                        relative,
                        literal.lineno,
                        UNWRAPPED_STRING,
                        f"user-visible string is not translated: {literal.value!r}",
                    )
                )
    return findings


def _sink_indices(node: ast.Call) -> tuple[int, ...] | None:
    function = node.func
    name = _call_name(function)
    if name is None:
        return None
    if isinstance(function, ast.Attribute):
        if name in _WIDGET_METHODS:
            return _WIDGET_METHODS[name]
        owner = _call_name(function.value)
        if owner in _DIALOG_STATICS and name in _DIALOG_STATICS[owner]:
            return _DIALOG_STATICS[owner][name]
        if name in _WIDGET_CONSTRUCTORS:
            return _WIDGET_CONSTRUCTORS[name]
        return None
    if name in _WIDGET_CONSTRUCTORS:
        return _WIDGET_CONSTRUCTORS[name]
    return None


def _call_name(node: ast.expr) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _inside_translation(node: ast.AST, parents: dict[int, ast.AST]) -> bool:
    current = parents.get(id(node))
    while current is not None:
        if isinstance(current, ast.Call) and _call_name(current.func) in TRANSLATION_CALLS:
            return True
        current = parents.get(id(current))
    return False


def _literal_parts(node: ast.AST):
    """Yield every string constant that can reach ``node`` as visible text."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        yield node
    elif isinstance(node, ast.JoinedStr):
        for value in node.values:
            if isinstance(value, ast.Constant) and isinstance(value.value, str):
                yield value
    elif isinstance(node, ast.BinOp):
        yield from _literal_parts(node.left)
        yield from _literal_parts(node.right)
    elif isinstance(node, ast.IfExp):
        yield from _literal_parts(node.body)
        yield from _literal_parts(node.orelse)
    elif isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        for element in node.elts:
            yield from _literal_parts(element)
    elif isinstance(node, ast.Call):
        for argument in node.args:
            yield from _literal_parts(argument)


def _visible_text(value: str) -> str:
    """The text a user reads, with markup, styles and entities removed."""
    text = _TAG.sub(" ", value)
    text = _STYLE.sub(" ", text)
    text = _ENTITY.sub(" ", text)
    return html.unescape(text)
