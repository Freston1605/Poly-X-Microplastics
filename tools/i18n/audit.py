# Dynamic translation calls and unwrapped widget text.
# ---------------------------------------------------------------------------


def audit_sources(root: Path) -> list[Finding]:
    """Check translation-call arguments and user-visible widget text."""
    findings: list[Finding] = []
    source_root = root / SOURCE
    if not source_root.is_dir():
        return findings

    for path in sorted(source_root.rglob("*.py")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        relative = path.relative_to(root).as_posix()
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        findings.extend(_dynamic_findings(relative, tree))
        if path.is_relative_to(root / GUI):
            findings.extend(_unwrapped_findings(relative, tree))
        if path.is_relative_to(root / CLI):
            findings.extend(_terminal_findings(relative, tree))
        if relative in HTML_SURFACES:
            findings.extend(_html_findings(relative, tree))
        if path.is_relative_to(root / REPORT):
            # The full report is a package of hand-built HTML: its words reach
            # the user through text nodes, so only markup literals are scanned.
            findings.extend(_html_findings(relative, tree, markup_only=True))

    return findings


def audit_spanish_literals(root: Path) -> list[Finding]:
    """Fail on Spanish string constants that never reach a catalog.

    The sink scan sees text passed to a Qt setter; it cannot see a Spanish
    sentence assigned to a variable and rendered later. This walk reads every
    string constant in ``src/polyx``, skips docstrings by AST kind, skips the
    arguments of a translation call (Spanish belongs in ``.po``, not in
    Python), and honours the small explicit allowlist above for log messages,
    citations and data tokens. Everything else is a leak.
    """
    findings: list[Finding] = []
    source_root = root / SOURCE
    if not source_root.is_dir():
        return findings

    for path in sorted(source_root.rglob("*.py")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        relative = path.relative_to(root).as_posix()
        try:
            tree = ast.parse(text)
        except SyntaxError:
            continue
        docstrings = _docstring_ids(tree)
        parents = _parents(tree)
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Constant) and isinstance(node.value, str)):
                continue
            if id(node) in docstrings:
                continue
            if not _SPANISH_CHARS.search(node.value):
                continue
            if _inside_translation(node, parents):
                continue
            if _spanish_is_exempt(relative, node.value):
                continue
            findings.append(
                Finding(
                    relative,
                    node.lineno,
                    SPANISH_LITERAL,
                    f"Spanish string literal bypasses the catalog: {node.value!r}",
                )
            )
    return findings


def _spanish_is_exempt(relative: str, literal: str) -> bool:
    """Whether a literal is out of scope, non-prose or a known data token."""
    if (relative, literal) in _SPANISH_ALLOWLIST:
        return True
    return any(
        path == relative and fragment in literal for path, fragment in _SPANISH_ALLOWED_FRAGMENTS
    )


def _dynamic_findings(relative: str, tree: ast.AST) -> list[Finding]:
    findings: list[Finding] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        function = _call_name(node.func)
        if function not in TRANSLATION_CALLS:
            continue
        for argument in node.args:
            if isinstance(argument, ast.JoinedStr):
                findings.append(
                    Finding(
                        relative,
                        argument.lineno,
                        DYNAMIC_CALL,
                        f"f-string passed to {function}(); use a named %(placeholder)s",
                    )
                )
            elif (
                isinstance(argument, ast.Constant)
                and isinstance(argument.value, str)
                and po.has_braces(argument.value)
            ):
                findings.append(
                    Finding(
                        relative,
                        argument.lineno,
                        DYNAMIC_CALL,
                        f"positional braces in {function}(): {argument.value!r}",
                    )
                )
            elif (
                isinstance(argument, ast.Call)
                and isinstance(argument.func, ast.Attribute)
                and argument.func.attr in {"format", "format_map"}
            ):
                findings.append(
                    Finding(
                        relative,
                        argument.lineno,
                        DYNAMIC_CALL,
                        f"str.format passed to {function}(); use a named %(placeholder)s",
                    )
                )
    return findings


def _unwrapped_findings(relative: str, tree: ast.AST) -> list[Finding]:
    parents = {
        id(child): parent for parent in ast.walk(tree) for child in ast.iter_child_nodes(parent)
    }
    findings: list[Finding] = []
    seen: set[tuple[int, str]] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        indices = _sink_indices(node)
        if indices is None:
            continue
        for index in indices:
            if index >= len(node.args):
                continue
            for literal in _literal_parts(node.args[index]):
                if _inside_translation(literal, parents):
                    continue
                visible = _visible_text(literal.value)
                if not _WORD.search(visible):
                    continue
                key = (literal.lineno, literal.value)
                if key in seen:
                    continue
                seen.add(key)
                findings.append(
                    Finding(
                        relative,
                        literal.lineno,
                        UNWRAPPED_STRING,
                        f"user-visible string is not translated: {literal.value!r}",
                    )
                )
    return findings


def _terminal_findings(relative: str, tree: ast.AST) -> list[Finding]:
    """Strings the CLI prints, shows as argparse help, or raises as an error.

    The Qt sink scan does not apply here: the command line has no widgets. Its
    visible text leaves through ``print``/``sys.stdout.write``, through the
    ``help`` and ``description`` keywords of argparse, and through the errors
    ``main`` catches and prints.
    """
    parents = _parents(tree)
    findings: list[Finding] = []
    seen: set[tuple[int, str]] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        name = _call_name(node.func)
        stream_write = (
            isinstance(node.func, ast.Attribute)
            and name == "write"
            and _call_name(node.func.value) in _STREAM_SINKS
        )
        candidates: list[ast.AST] = []
        if name in _PRINT_SINKS or stream_write or name in _CLI_ERROR_SINKS:
            candidates.extend(node.args[:1])
        keywords = _ARGUMENT_KEYWORDS.get(name or "")
        if keywords:
            candidates.extend(keyword.value for keyword in node.keywords if keyword.arg in keywords)
        for candidate in candidates:
            for literal in _literal_parts(candidate):
                if _inside_translation(literal, parents):
                    continue
                visible = _visible_text(literal.value)
                if not _WORD.search(visible):
                    continue
                key = (literal.lineno, literal.value)
                if key in seen:
                    continue
                seen.add(key)
                findings.append(
                    Finding(
                        relative,
                        literal.lineno,
                        UNWRAPPED_STRING,
                        f"user-visible string is not translated: {literal.value!r}",
                    )
                )
    return findings


def _html_findings(relative: str, tree: ast.AST, *, markup_only: bool = False) -> list[Finding]:
    """Prose in a hand-built HTML document: text nodes and display labels.

    ``report_simple`` and the training summary write their document as a
    string, so their words never reach a Qt setter. Two shapes are visible
    here: text between tags (a heading, a caption, a meta line) and a plain
    literal with several words (a figure caption, an error message). CSS
    blocks are skipped, and bibliography entries are recognised by their
    parenthesised year: citations are never translated.

    ``markup_only`` is for the report package, where most literals are data,
    matplotlib keyword values or dictionary keys. Only a literal that carries
    HTML can put a word in front of the reader, so a non-markup literal is
    ignored instead of being reported as a bare label.
    """
    parents = _parents(tree)
    docstrings = _docstring_ids(tree)
    joined_parts = {
        id(child)
        for node in ast.walk(tree)
        if isinstance(node, ast.JoinedStr)
        for child in node.values
    }
    findings: list[Finding] = []
    seen: set[tuple[int, str]] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            value = "".join(
                part.value
                for part in node.values
                if isinstance(part, ast.Constant) and isinstance(part.value, str)
            )
        elif (
            isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and id(node) not in docstrings
            and id(node) not in joined_parts
        ):
            value = node.value
        else:
            continue
        if _inside_translation(node, parents):
            continue
        if "{" in value:
            # A style block, not prose: report_simple and the summary keep
            # their CSS in a string literal too.
            continue
        has_markup = re.search(r"<[A-Za-z]", value) is not None
        if markup_only and not has_markup:
            continue
        if has_markup and _CITATION.search(value):
            # A bibliography entry may span several lines: the year marks the
            # whole literal as a citation, not just the line it appears on.
            continue
        for line in value.splitlines() or [value]:
            text = _visible_text(line).strip()
            if has_markup:
                check = _without_neutral_tokens(text)
            else:
                check = text
                if not _PROSE.search(check):
                    continue
            if not _WORD.search(check):
                continue
            key = (node.lineno, text)
            if key in seen:
                continue
            seen.add(key)
            findings.append(
                Finding(
                    relative,
                    node.lineno,
                    UNWRAPPED_STRING,
                    f"user-visible string is not translated: {text!r}",
                )
            )
    return findings


def _without_neutral_tokens(text: str) -> str:
    """Drop the tokens that read the same in every language."""
    for word in _MACHINE_WORDS:
        text = re.sub(rf"\b{re.escape(word)}\b", " ", text)
    text = _UNITS.sub(" ", text)
    return _CREDIT.sub(" ", text)


def _parents(tree: ast.AST) -> dict[int, ast.AST]:
    return {
        id(child): parent for parent in ast.walk(tree) for child in ast.iter_child_nodes(parent)
    }


def _docstring_ids(tree: ast.AST) -> set[int]:
    """The constant nodes that are docstrings, which are never interface text."""
    found: set[int] = set()
    holders = (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
    for node in ast.walk(tree):
        if not isinstance(node, holders):
            continue
        body = node.body
        if (
            body
            and isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)
        ):
            found.add(id(body[0].value))
    return found


def _sink_indices(node: ast.Call) -> tuple[int, ...] | None:
    function = node.func
    name = _call_name(function)
    if name is None:
        return None
    if isinstance(function, ast.Attribute):
        if name in _WIDGET_METHODS:
            return _WIDGET_METHODS[name]
        owner = _call_name(function.value)
        if owner in _DIALOG_STATICS and name in _DIALOG_STATICS[owner]:
            return _DIALOG_STATICS[owner][name]
        if name in _WIDGET_CONSTRUCTORS:
            return _WIDGET_CONSTRUCTORS[name]
        return None
    if name in _WIDGET_CONSTRUCTORS:
        return _WIDGET_CONSTRUCTORS[name]
    return None


def _call_name(node: ast.expr) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _inside_translation(node: ast.AST, parents: dict[int, ast.AST]) -> bool:
    current = parents.get(id(node))
    while current is not None:
        if isinstance(current, ast.Call) and _call_name(current.func) in TRANSLATION_CALLS:
            return True
        current = parents.get(id(current))
    return False


def _literal_parts(node: ast.AST):
    """Yield every string constant that can reach ``node`` as visible text."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        yield node
    elif isinstance(node, ast.JoinedStr):
        for value in node.values:
            if isinstance(value, ast.Constant) and isinstance(value.value, str):
                yield value
    elif isinstance(node, ast.BinOp):
        yield from _literal_parts(node.left)
        yield from _literal_parts(node.right)
    elif isinstance(node, ast.IfExp):
        yield from _literal_parts(node.body)
        yield from _literal_parts(node.orelse)
    elif isinstance(node, (ast.List, ast.Tuple, ast.Set)):
        for element in node.elts:
            yield from _literal_parts(element)
    elif isinstance(node, ast.Call):
        for argument in node.args:
            yield from _literal_parts(argument)


def _visible_text(value: str) -> str:
    """The text a user reads, with markup, styles and entities removed."""
    text = _TAG.sub(" ", value)
    text = _STYLE.sub(" ", text)
    text = _ENTITY.sub(" ", text)
    return html.unescape(text)
