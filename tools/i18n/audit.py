_WORD = re.compile(r"[^\W\d_]{2,}", re.UNICODE)


@dataclass(frozen=True, order=True)
class Finding:
    """One drift, located where the fix belongs."""

    path: str
    line: int
    kind: str
    detail: str

    def __str__(self) -> str:
        location = f"{self.path}:{self.line}" if self.line else self.path
        return f"{location}: {self.kind}: {self.detail}"


# ---------------------------------------------------------------------------
# Entry points.
# ---------------------------------------------------------------------------


def audit_tree(root: Path) -> list[Finding]:
    """Run every check over a checkout and return the sorted findings."""
    findings = (
        audit_sources(root)
        + audit_spanish_literals(root)
        + audit_template(root)
        + audit_catalogs(root)
    )
    return sorted(set(findings))


def report(findings: list[Finding], stream=None) -> None:
    """Print one line per finding, the shape a log reader can grep."""
    import sys

    target = stream or sys.stderr
    for finding in findings:
        print(finding, file=target)


# ---------------------------------------------------------------------------
# Stale template.
# ---------------------------------------------------------------------------


def audit_template(root: Path) -> list[Finding]:
    """Compare the committed template with a fresh walk of the source tree."""
    template = root / TEMPLATE
    if not template.is_file():
        return [
            Finding(
                TEMPLATE.as_posix(),
                0,
                STALE_TEMPLATE,
                "committed template is missing; run `python tools/i18n/cli.py extract`",
            )
        ]

    source = _source_entries(root)
    committed = _template_entries(template)
    findings: list[Finding] = []

    for key in sorted(source.keys() - committed.keys(), key=_sort_key):
        locations = sorted(source[key])
        path, line = locations[0]
        findings.append(
            Finding(
                path,
                line,
                STALE_TEMPLATE,
                f"template is missing {_describe(key)}; run `python tools/i18n/cli.py extract`",
            )
        )

    for key in sorted(committed.keys() - source.keys(), key=_sort_key):
        entry = committed[key]
        findings.append(
            Finding(
                TEMPLATE.as_posix(),
                entry.lineno,
                STALE_TEMPLATE,
                f"template has {_describe(key)} that no source uses",
            )
        )

    for key in sorted(source.keys() & committed.keys(), key=_sort_key):
        expected = set(source[key])
        actual = set(committed[key].locations)
        if expected != actual:
            findings.append(
                Finding(
                    TEMPLATE.as_posix(),
                    committed[key].lineno,
                    STALE_TEMPLATE,
                    f"locations changed for {_describe(key)}: "
                    f"template {_locations(actual)}, source {_locations(expected)}",
                )
            )

    return findings


def _source_entries(root: Path) -> dict[tuple[str | None, object], list[tuple[str, int]]]:
    """Every message in the source tree, with the places it appears."""
    entries: dict[tuple[str | None, object], list[tuple[str, int]]] = {}
    source_root = root / SOURCE
    if not source_root.is_dir():
        return entries
    for path in sorted(source_root.rglob("*.py")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        relative = path.relative_to(root).as_posix()
        for message in iter_source_messages(text):
            entries.setdefault((message.context, message.message), []).append(
                (relative, message.line)
            )
    return entries


def _template_entries(template: Path) -> dict[tuple[str | None, object], po.PoEntry]:
    entries: dict[tuple[str | None, object], po.PoEntry] = {}
    for entry in po.parse_po(template.read_text(encoding="utf-8")):
        if entry.obsolete or not entry.msgid:
            continue
        entries[entry.key] = entry
    return entries


def _describe(key: tuple[str | None, object]) -> str:
    context, message = key
    if isinstance(message, tuple):
        rendered = f"plural {message[0]!r} / {message[1]!r}"
    else:
        rendered = f"msgid {message!r}"
    return f"context {context!r}: {rendered}" if context else rendered


def _sort_key(key: tuple[str | None, object]) -> tuple[str, str, str]:
    """Order keys without comparing a singular string to a plural tuple."""
    context, message = key
    return (context or "", type(message).__name__, repr(message))


def _locations(locations: set[tuple[str, int]]) -> str:
    return ", ".join(f"{path}:{line}" for path, line in sorted(locations))


# ---------------------------------------------------------------------------
# Catalog translations.
# ---------------------------------------------------------------------------


def audit_catalogs(root: Path) -> list[Finding]:
    """Check every shipped catalog: present, translated, placeholders intact."""
    template = root / TEMPLATE
    template_entries = _template_entries(template) if template.is_file() else {}
    findings: list[Finding] = []

    for catalog in sorted((root / LOCALES).glob("*/LC_MESSAGES/*.po")):
        if catalog.parent.parent.name == PSEUDO_TAG:
            continue
        relative = catalog.relative_to(root).as_posix()
        entries = [
            entry
            for entry in po.parse_po(catalog.read_text(encoding="utf-8"))
            if not entry.obsolete
        ]
        by_key = {entry.key: entry for entry in entries if entry.msgid}
        findings.extend(_catalog_findings(relative, entries))

        for key in sorted(template_entries.keys() - by_key.keys(), key=_sort_key):
            template_entry = template_entries[key]
            location = (
                template_entry.locations[0]
                if template_entry.locations
                else (TEMPLATE.as_posix(), 0)
            )
            findings.append(
                Finding(
                    location[0],
                    location[1],
                    EMPTY_TRANSLATION,
                    f"{_describe(key)} is missing from {relative}",
                )
            )

    return findings


def _catalog_findings(relative: str, entries: list[po.PoEntry]) -> list[Finding]:
    findings: list[Finding] = []
    for entry in entries:
        if not entry.msgid:
            continue
        if entry.fuzzy:
            findings.append(
                Finding(
                    relative,
                    entry.lineno,
                    EMPTY_TRANSLATION,
                    f"{_describe(entry.key)} is fuzzy and is ignored at runtime",
                )
            )
            continue
        if entry.is_plural:
            findings.extend(_plural_findings(relative, entry))
        else:
            findings.extend(_singular_findings(relative, entry))
    return findings


def _singular_findings(relative: str, entry: po.PoEntry) -> list[Finding]:
    if not entry.msgstr.strip():
        return [
            Finding(
                relative,
                entry.lineno,
                EMPTY_TRANSLATION,
                f"{_describe(entry.key)} has an empty translation",
            )
        ]
    return _placeholder_findings(relative, entry, entry.msgid, entry.msgstr, "translation")


def _plural_findings(relative: str, entry: po.PoEntry) -> list[Finding]:
    forms = sorted(entry.msgstr_plural)
    if not forms:
        return [
            Finding(
                relative,
                entry.lineno,
                EMPTY_TRANSLATION,
                f"{_describe(entry.key)} has no plural translation",
            )
        ]
    findings: list[Finding] = []
    for index in forms:
        value = entry.msgstr_plural[index]
        if not value.strip():
            findings.append(
                Finding(
                    relative,
                    entry.lineno,
                    EMPTY_TRANSLATION,
                    f"{_describe(entry.key)} has an empty plural form {index}",
                )
            )
            continue
        expected_id = entry.msgid if index == 0 else entry.msgid_plural
        findings.extend(
            _placeholder_findings(
                relative, entry, expected_id or entry.msgid, value, f"plural form {index}"
            )
        )
    return findings


def _placeholder_findings(
    relative: str,
    entry: po.PoEntry,
    message_id: str,
    translation: str,
    label: str,
) -> list[Finding]:
    if po.has_braces(translation):
        return [
            Finding(
                relative,
                entry.lineno,
                PLACEHOLDER_MISMATCH,
                f"{label} for {_describe(entry.key)} uses braces: {translation!r}",
            )
        ]
    expected = po.format_placeholders(message_id)
    actual = po.format_placeholders(translation)
    if expected == actual:
        return []
    return [
        Finding(
            relative,
            entry.lineno,
            PLACEHOLDER_MISMATCH,
            f"{label} for {_describe(entry.key)} expects {sorted(expected)} "
            f"but has {sorted(actual)}",
        )
    ]


